def _increment(d):
    return 1.20 * d[:, -1] - .25 * d[:, -2] - .05 * d[:, -3]

def _amplitude(d):
    return np.sqrt(.0121 + (d[:, -4:] ** 2 * _AW).sum(axis=1)) / .16

