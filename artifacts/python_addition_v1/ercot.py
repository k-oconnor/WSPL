def _neighbors(distance, residual, count, prior=None, floor=.0015):
    ix = np.argpartition(distance, count - 1, axis=1)[:, :count]
    ds = np.take_along_axis(distance, ix, axis=1)
    weight = 1.0 / (ds + floor) ** 2
    if prior is not None:
        weight *= prior[ix]
    correction = (weight * residual[ix]).sum(axis=1) / weight.sum(axis=1)
    confidence = .90 / (1.0 + np.maximum(ds.min(axis=1) - .012, 0.0) / .08)
    return correction * confidence

def predict(x):
    a = np.asarray(x, dtype=np.float64)
    a = np.nan_to_num(a, nan=0.0, posinf=1e6, neginf=-1e6)
    z = np.clip(a, -1e6, 1e6) * _SCALE + _OFFSET
    result = np.empty((len(z), 1), dtype=np.float32)

    for start in range(0, len(z), 256):
        q = z[start:start + 256]
        d = np.diff(q, axis=1)
        amp = _amplitude(d)
        dn = d / amp[:, None]

        raw_distance = np.zeros((len(q), len(_D)), dtype=np.float64)
        shape_distance = np.zeros_like(raw_distance)
        for j in range(7):
            e = d[:, j, None] - _D[None, :, j]
            raw_distance += e * e * _MW[None, :, j]
            e = dn[:, j, None] - _DN[None, :, j]
            shape_distance += e * e * _MW[None, :, j]

        raw_distance *= _NORMALIZER[None, :]
        shape_distance *= _NORMALIZER[None, :]

        level_distance = (q[:, -1, None] - _L[None, :]) ** 2
        raw_distance += .006 * level_distance
        raw_distance += .12 * (
            d[:, -3:].sum(axis=1)[:, None] - _RECENT[None, :]
        ) ** 2

        # A complementary analogue metric compares amplitude-normalized shapes.
        shape_distance += .005 * level_distance
        shape_distance += .006 * (amp[:, None] - _AMP[None, :]) ** 2
        for span, weight in ((3, .12), (5, .025), (7, .006)):
            e = dn[:, -span:].sum(axis=1)[:, None] - _NSUMS[span][None, :]
            shape_distance += weight * e * e * _M[None, :, -span]

        raw_correction = _neighbors(raw_distance, _RESIDUAL, 16)
        shape_correction = amp * _neighbors(
            shape_distance, _RN, 20, prior=_PRIOR, floor=.002
        )

        prediction = (
            q[:, -1] + _increment(d)
            + .65 * raw_correction + .35 * shape_correction
        )

        nearest = np.argmin(raw_distance, axis=1)
        exact = raw_distance[np.arange(len(q)), nearest] < 1e-10
        prediction = np.where(exact, q[:, -1] + _Y[nearest], prediction)

        result[start:start + len(q), 0] = np.clip(
            np.nan_to_num(prediction, nan=0.0, posinf=1e6, neginf=-1e6),
            -1e6, 1e6
        ).astype(np.float32)

    return result