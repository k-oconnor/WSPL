def _features_and_reference(c, a):
    c = np.clip(c, .05, 10.)
    d = np.clip(a[:, 0], -6., 6.)
    t = np.clip(a[:, 1], -6., 6.)

    length = np.clip(
        5.826953125 + 1.0264338740526515 * a[:, 2], .1, 25.
    )
    width = np.clip(
        5.8353125 + 1.0268808486595462 * a[:, 3], .1, 25.
    )
    height = np.clip(
        3.6015625 + .6448745487253703 * a[:, 4], .1, 20.
    )
    volume_ratio = np.clip(length * width * height / c, 130., 195.)

    lc = np.log(c)
    rounded_c = np.round(c, 4)

    reference = .63 + 1.50 * lc
    reference -= .10 * (rounded_c < 1.00)
    reference -= .15 * (rounded_c < .90)
    reference -= .07 * (rounded_c < .70)
    reference -= .10 * (rounded_c < .50)
    reference -= .06 * (rounded_c < .40)
    reference -= .06 * (rounded_c < .30)
    reference += .08 * (rounded_c >= 1.50)
    reference += .10 * (rounded_c >= 2.00)

    # Gentler extrapolation for the smallest stones.
    reference += .35 * np.maximum(np.log(.30) - lc, 0.)

    reference -= .025 * d * d + .015 * d + .025 * t
    reference += .010 * np.clip(volume_ratio - 163., -18., 18.)

    return np.column_stack((lc, d, t, volume_ratio)), reference


